    ('Red', 'Equipos de conectividad');

-- Agregar la columna del tipo a la tabla de equipos
ALTER TABLE laboratorio.equipo
ADD COLUMN id_tipo BIGINT;

-- Asignar un tipo a cada equipo
UPDATE laboratorio.equipo
SET id_tipo = (SELECT id_tipo FROM laboratorio.tipo_equipo WHERE nombre = 'Computadora')
WHERE codigo IN ('C1', 'C2', 'C3');

UPDATE laboratorio.equipo
SET id_tipo = (SELECT id_tipo FROM laboratorio.tipo_equipo WHERE nombre = 'Proyector')
WHERE codigo IN ('P1', 'P2', 'P3');

UPDATE laboratorio.equipo
SET id_tipo = (SELECT id_tipo FROM laboratorio.tipo_equipo WHERE nombre = 'Red')
WHERE codigo IN ('R1', 'R2');

-- No permitir equipos sin tipo
ALTER TABLE laboratorio.equipo
ALTER COLUMN id_tipo SET NOT NULL;

-- Relacionar equipos con tipos
ALTER TABLE laboratorio.equipo
ADD CONSTRAINT fk_tipo_equipo FOREIGN KEY (id_tipo)
REFERENCES laboratorio.tipo_equipo (id_tipo);

-- Comprobar la relacion
SELECT e.codigo, e.nombre, e.estado, e.cantidad, t.nombre AS tipo
FROM laboratorio.equipo e
JOIN laboratorio.tipo_equipo t ON t.id_tipo = e.id_tipo
ORDER BY e.id_equipo;


