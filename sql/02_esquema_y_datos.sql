-- Esquema
CREATE SCHEMA IF NOT EXISTS laboratorio;

-- Tabla de equipos
CREATE TABLE laboratorio.equipo (
    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    estado VARCHAR(30) NOT NULL,
    cantidad INTEGER,
    CONSTRAINT chk_estado CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio')),
    CONSTRAINT chk_cantidad CHECK (cantidad >= 0)
);

